import { mkdirSync, mkdtempSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

type Preset = { id: string; name: string };

const TILE = 512;
const COLUMNS = [64, 736, 1408];
const ROW_STEP = 672;

const SHEET = "contrib/disguise/disguises.svg";
const MONO_SHEET = "contrib/disguise/disguises-mono.svg";
const ORIGINAL_ICON = "contrib/logo/app-icon.svg";
const ORIGINAL_BACKGROUND = "#0A0A0A";
const PRESETS = "src-tauri/src/disguise/presets.json";
const DESKTOP_ICONS = "src-tauri/src/disguise/icons";
const PREVIEWS = "src/lib/assets/disguise";
const ANDROID = "src-tauri/gen/android/app/src/main";
const ANDROID_RES = `${ANDROID}/res`;
const MANIFEST = `${ANDROID}/AndroidManifest.xml`;
const ALIASES_BEGIN =
	"<!-- disguise aliases: generated by scripts/gen-disguise-icons.ts -->";
const ALIASES_END = "<!-- end of disguise aliases -->";

const ANDROID_LAYER = 432;
const ANDROID_TILE = 288;
const NOTIFICATION_CANVAS = 96;
const NOTIFICATION_LIVE_AREA = 80;
const MACOS_BODY = 412;
const MACOS_RADIUS = 92.7;
const WINDOWS_SIZES = [256, 64, 48, 40, 32, 24, 20, 16];
const LINUX_SIZE = 256;
const PREVIEW_SIZE = 128;

const PNG = ["-strip", "-define", "png:exclude-chunks=date,time"];

function run(command: string, args: string[]) {
	const result = Bun.spawnSync([command, ...args], {
		stdout: "inherit",
		stderr: "inherit",
	});
	if (!result.success)
		throw new Error(
			`${command} ${args.join(" ")} exited ${result.exitCode}`,
		);
}

function magick(...args: string[]) {
	run("magick", args);
}

function resourceName(preset: Preset) {
	return `disguise_${preset.id.replaceAll("-", "_")}`;
}

function aliasName(preset: Preset) {
	return preset.id
		.split("-")
		.map((word) => word[0]!.toUpperCase() + word.slice(1))
		.join("");
}

function xmlText(value: string) {
	return value
		.replaceAll("&", "&amp;")
		.replaceAll("<", "&lt;")
		.replaceAll(">", "&gt;")
		.replaceAll('"', "&quot;");
}

function androidString(value: string) {
	return xmlText(value).replaceAll("'", "\\'");
}

function tileOrigin(index: number) {
	return {
		x: COLUMNS[index % COLUMNS.length]!,
		y: Math.floor(index / COLUMNS.length) * ROW_STEP,
	};
}

async function assertSheetOrder(sheet: string, presets: Preset[]) {
	const text = await Bun.file(sheet).text();
	let previous = -1;
	for (const preset of presets) {
		const position = text.indexOf(`<g id="${xmlText(preset.name)}"`);
		if (position <= previous)
			throw new Error(
				`${sheet}: tile "${preset.name}" is missing or out of order`,
			);
		previous = position;
	}
}

function cropTiles(
	sheet: string,
	presets: Preset[],
	scratch: string,
	suffix: string,
) {
	const rendered = join(scratch, `sheet${suffix}.png`);
	run("rsvg-convert", [sheet, "-o", rendered]);
	return presets.map((preset, index) => {
		const { x, y } = tileOrigin(index);
		const tile = join(scratch, `${preset.id}${suffix}.png`);
		magick(rendered, "-crop", `${TILE}x${TILE}+${x}+${y}`, "+repage", tile);
		return tile;
	});
}

function clearGenerated(directory: string, prefix: string) {
	mkdirSync(directory, { recursive: true });
	for (const file of readdirSync(directory))
		if (file.startsWith(prefix)) rmSync(join(directory, file));
}

function writeAndroidIcons(preset: Preset, tile: string, monoTile: string) {
	const name = resourceName(preset);
	const bleed = (ANDROID_LAYER - ANDROID_TILE) / 2;
	magick(
		tile,
		"-resize",
		`${ANDROID_TILE}x${ANDROID_TILE}`,
		"-virtual-pixel",
		"edge",
		"-set",
		"option:distort:viewport",
		`${ANDROID_LAYER}x${ANDROID_LAYER}-${bleed}-${bleed}`,
		"-distort",
		"SRT",
		"0",
		"+repage",
		...PNG,
		`${ANDROID_RES}/mipmap-xxxhdpi/${name}_foreground.png`,
	);
	magick(
		monoTile,
		"-resize",
		`${ANDROID_TILE}x${ANDROID_TILE}`,
		"-background",
		"none",
		"-gravity",
		"center",
		"-extent",
		`${ANDROID_LAYER}x${ANDROID_LAYER}`,
		...PNG,
		`${ANDROID_RES}/mipmap-xxxhdpi/${name}_monochrome.png`,
	);
	magick(
		monoTile,
		"-trim",
		"+repage",
		"-resize",
		`${NOTIFICATION_LIVE_AREA}x${NOTIFICATION_LIVE_AREA}`,
		"-background",
		"none",
		"-gravity",
		"center",
		"-extent",
		`${NOTIFICATION_CANVAS}x${NOTIFICATION_CANVAS}`,
		...PNG,
		`${ANDROID_RES}/drawable-xxxhdpi/${name}_notification.png`,
	);
	return Bun.write(
		`${ANDROID_RES}/mipmap-anydpi-v26/${name}.xml`,
		[
			`<?xml version="1.0" encoding="utf-8"?>`,
			`<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">`,
			`  <background android:drawable="@color/ic_launcher_background"/>`,
			`  <foreground android:drawable="@mipmap/${name}_foreground"/>`,
			`  <monochrome android:drawable="@mipmap/${name}_monochrome"/>`,
			`</adaptive-icon>`,
			``,
		].join("\n"),
	);
}

async function writeIco(tile: string, scratch: string, output: string) {
	const frames = await Promise.all(
		WINDOWS_SIZES.map(async (size) => {
			const frame = join(scratch, `ico-${size}.png`);
			magick(
				tile,
				"-resize",
				`${size}x${size}`,
				...PNG,
				`PNG32:${frame}`,
			);
			return {
				size,
				data: new Uint8Array(await Bun.file(frame).arrayBuffer()),
			};
		}),
	);
	const directorySize = 6 + 16 * frames.length;
	const header = new DataView(new ArrayBuffer(directorySize));
	header.setUint16(2, 1, true);
	header.setUint16(4, frames.length, true);
	let offset = directorySize;
	for (const [index, { size, data }] of frames.entries()) {
		const entry = 6 + 16 * index;
		header.setUint8(entry, size % 256);
		header.setUint8(entry + 1, size % 256);
		header.setUint16(entry + 4, 1, true);
		header.setUint16(entry + 6, 32, true);
		header.setUint32(entry + 8, data.byteLength, true);
		header.setUint32(entry + 12, offset, true);
		offset += data.byteLength;
	}
	await Bun.write(
		output,
		new Blob([header, ...frames.map(({ data }) => data)]),
	);
}

async function writeDesktopIcons(
	preset: Preset,
	tile: string,
	scratch: string,
) {
	await writeIco(tile, scratch, `${DESKTOP_ICONS}/windows/${preset.id}.ico`);
	magick(
		tile,
		"-resize",
		`${LINUX_SIZE}x${LINUX_SIZE}`,
		...PNG,
		`${DESKTOP_ICONS}/linux/${preset.id}.png`,
	);
	const mask = join(scratch, "macos-mask.png");
	const inset = (TILE - MACOS_BODY) / 2;
	magick(
		"-size",
		`${TILE}x${TILE}`,
		"xc:none",
		"-fill",
		"white",
		"-draw",
		`roundrectangle ${inset},${inset} ${inset + MACOS_BODY - 1},${inset + MACOS_BODY - 1} ${MACOS_RADIUS},${MACOS_RADIUS}`,
		mask,
	);
	magick(
		tile,
		"-resize",
		`${MACOS_BODY}x${MACOS_BODY}`,
		"-background",
		"none",
		"-gravity",
		"center",
		"-extent",
		`${TILE}x${TILE}`,
		mask,
		"-compose",
		"DstIn",
		"-composite",
		...PNG,
		`PNG32:${DESKTOP_ICONS}/macos/${preset.id}.png`,
	);
}

function writePreview(id: string, tile: string) {
	magick(
		tile,
		"-resize",
		`${PREVIEW_SIZE}x${PREVIEW_SIZE}`,
		"-strip",
		"-define",
		"webp:lossless=true",
		`${PREVIEWS}/${id}.webp`,
	);
}

function writeOriginalPreview(scratch: string) {
	const rendered = join(scratch, "original.png");
	run("rsvg-convert", [
		"-w",
		String(PREVIEW_SIZE),
		"-h",
		String(PREVIEW_SIZE),
		"-b",
		ORIGINAL_BACKGROUND,
		ORIGINAL_ICON,
		"-o",
		rendered,
	]);
	writePreview("original", rendered);
}

function aliasElement({
	name,
	enabled,
	icon,
	label,
	id,
	notificationIcon,
}: {
	name: string;
	enabled: boolean;
	icon: string;
	label: string;
	id: string;
	notificationIcon: string;
}) {
	return [
		`\t\t<activity-alias`,
		`\t\t\tandroid:enabled="${enabled}"`,
		`\t\t\tandroid:exported="true"`,
		`\t\t\tandroid:icon="${icon}"`,
		`\t\t\tandroid:label="${label}"`,
		`\t\t\tandroid:name="${name}"`,
		`\t\t\tandroid:targetActivity=".AppActivity">`,
		`\t\t\t<intent-filter>`,
		`\t\t\t\t<action android:name="android.intent.action.MAIN" />`,
		`\t\t\t\t<category android:name="android.intent.category.LAUNCHER" />`,
		`\t\t\t</intent-filter>`,
		`\t\t\t<meta-data android:name="org.opengrind.disguise" android:value="${id}" />`,
		`\t\t\t<meta-data android:name="org.opengrind.disguise.notification_icon" android:resource="${notificationIcon}" />`,
		`\t\t</activity-alias>`,
	].join("\n");
}

async function writeManifestAliases(presets: Preset[]) {
	const aliases = [
		aliasElement({
			name: ".MainActivity",
			enabled: true,
			icon: "@mipmap/ic_launcher",
			label: "@string/main_activity_title",
			id: "original",
			notificationIcon: "@drawable/ic_notification",
		}),
		...presets.map((preset) =>
			aliasElement({
				name: `.disguise.${aliasName(preset)}`,
				enabled: false,
				icon: `@mipmap/${resourceName(preset)}`,
				label: `@string/${resourceName(preset)}`,
				id: preset.id,
				notificationIcon: `@drawable/${resourceName(preset)}_notification`,
			}),
		),
	];
	const manifest = await Bun.file(MANIFEST).text();
	const begin = manifest.indexOf(ALIASES_BEGIN);
	const end = manifest.indexOf(ALIASES_END);
	if (begin < 0 || end < begin)
		throw new Error(`${MANIFEST}: missing the disguise alias markers`);
	await Bun.write(
		MANIFEST,
		manifest.slice(0, begin + ALIASES_BEGIN.length) +
			`\n${aliases.join("\n")}\n\t\t` +
			manifest.slice(end),
	);
}

async function writeDesktopIconTable(presets: Preset[]) {
	const platforms = [
		{ os: "linux", file: (id: string) => `linux/${id}.png` },
		{ os: "macos", file: (id: string) => `macos/${id}.png` },
		{ os: "windows", file: (id: string) => `windows/${id}.ico` },
	];
	const tables = platforms.map(({ os, file }) =>
		[
			`#[cfg(target_os = "${os}")]`,
			`pub(super) const ICONS: &[(&str, &[u8])] = &[`,
			...presets.map(
				(preset) =>
					`\t("${preset.id}", include_bytes!("icons/${file(preset.id)}")),`,
			),
			`];`,
		].join("\n"),
	);
	const output = "src-tauri/src/disguise/icons.rs";
	await Bun.write(output, `${tables.join("\n\n")}\n`);
	run("rustfmt", ["--edition", "2021", output]);
}

async function writeAndroidStrings(presets: Preset[]) {
	const strings = presets.map(
		(preset) =>
			`  <string name="${resourceName(preset)}" translatable="false">${androidString(preset.name)}</string>`,
	);
	await Bun.write(
		`${ANDROID_RES}/values/disguise.xml`,
		[
			`<?xml version="1.0" encoding="utf-8"?>`,
			`<resources>`,
			...strings,
			`</resources>`,
			``,
		].join("\n"),
	);
}

async function main() {
	const presets: Preset[] = await Bun.file(PRESETS).json();
	await assertSheetOrder(SHEET, presets);
	await assertSheetOrder(MONO_SHEET, presets);

	const scratch = mkdtempSync(join(tmpdir(), "disguise-icons-"));
	try {
		const tiles = cropTiles(SHEET, presets, scratch, "");
		const monoTiles = cropTiles(MONO_SHEET, presets, scratch, "-mono");

		clearGenerated(`${ANDROID_RES}/mipmap-xxxhdpi`, "disguise_");
		clearGenerated(`${ANDROID_RES}/drawable-xxxhdpi`, "disguise_");
		clearGenerated(`${ANDROID_RES}/mipmap-anydpi-v26`, "disguise_");
		for (const platform of ["windows", "linux", "macos"])
			clearGenerated(`${DESKTOP_ICONS}/${platform}`, "");
		clearGenerated(PREVIEWS, "");

		for (const [index, preset] of presets.entries()) {
			await writeAndroidIcons(preset, tiles[index]!, monoTiles[index]!);
			await writeDesktopIcons(preset, tiles[index]!, scratch);
			writePreview(preset.id, tiles[index]!);
		}
		writeOriginalPreview(scratch);
		await writeDesktopIconTable(presets);
		await writeAndroidStrings(presets);
		await writeManifestAliases(presets);
	} finally {
		rmSync(scratch, { recursive: true, force: true });
	}
}

await main();
